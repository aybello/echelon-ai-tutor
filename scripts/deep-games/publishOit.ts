/**
 * Assemble the OIT deep-game package from the existing tasks plus generated ladder tasks, stamp receipts and write
 * server/deepGames/content/oit.ts. Run only AFTER the second-model review of every task has passed.
 * Usage: node --import tsx scripts/deep-games/publishOit.ts <draft.json> <review.json>
 */
import { readFileSync, writeFileSync } from "node:fs";
import existing from "../../server/deepGames/content/oit";
import { deepPayloadSha256, validateDeepCoursePackage } from "../../server/deepGames/schema";

const [draftPath, reviewPath] = process.argv.slice(2);
if (!draftPath || !reviewPath) throw new Error("Usage: publishOit.ts <draft.json> <review.json>");
const draft = JSON.parse(readFileSync(draftPath, "utf8"));
const review = JSON.parse(readFileSync(reviewPath, "utf8"));
if (review.model !== "gpt-6.2-sol") throw new Error("Review file is not from gpt-6.2-sol");
const failed = review.results.filter((r: { verdict: string }) => r.verdict !== "ok");
if (failed.length || review.missing.length) throw new Error(`Review not clean: ${failed.length} not ok, ${review.missing.length} missing`);

const nextRevision = (r: string) => `r${Number(r.replace(/^r/, "")) + 1}`;
const tasks: any[] = JSON.parse(JSON.stringify(existing.tasks));
const missions: any[] = JSON.parse(JSON.stringify(existing.missions));

// Correction found by the review: apparent colour includes true colour and the suspended part that filtration removes.
const ev = tasks.find(t => t.id === "oit-evidence01");
const OLD = "True color remains after filtration, whereas apparent color is caused by suspended or colloidal matter that filtration removes.";
if (ev && ev.inference.explanation === OLD) {
  ev.inference.explanation = "Apparent color is the total color measured before clarification and includes true color plus color from suspended or colloidal matter. Filtration removes the suspended part, so the color that remains after filtration is true color.";
  ev.revision = nextRevision(ev.revision);
  for (const m of missions) {
    let touched = false;
    for (const ref of m.tasks) if (ref.taskId === "oit-evidence01") { ref.revision = ev.revision; touched = true; }
    if (touched) m.revision = nextRevision(m.revision);
  }
}

const oldReceipts = new Map(existing.publication.taskReceipts.map(r => [r.taskId, r.sourceIds]));
const newTasks = draft.tasks.map(({ _source, _family, ...task }: any) => ({ task, source: _source }));
const allTasks = [...tasks, ...newTasks.map((x: any) => x.task)];
const taskReceipts = [
  ...tasks.map(t => ({ taskId: t.id, revision: t.revision, sha256: deepPayloadSha256(t), sourceIds: oldReceipts.get(t.id)! })),
  ...newTasks.map((x: any) => ({ taskId: x.task.id, revision: x.task.revision, sha256: deepPayloadSha256(x.task), sourceIds: [x.source] })),
];
const sources = [...existing.sources, ...draft.sources];
const version = "deep-20261121-v3";
const core = { courseKey: "oit" as const, version, tasks: allTasks, missions };
const pkg = {
  ...core, sources,
  publication: {
    published: true as const, reviewedBy: "owner-authorized-ai-review:gpt-6.2-sol", reviewedAt: new Date().toISOString(),
    packageSha256: deepPayloadSha256(core), taskReceipts,
    missionReceipts: missions.map(m => ({ missionId: m.id, revision: m.revision, sha256: deepPayloadSha256(m) })),
  },
};
validateDeepCoursePackage(pkg, "oit"); // throws if anything is inconsistent

const header = `/** Water-treatment study content for OIT. Calculation Ladder tasks 005 onward are generated by scripts/deep-games/ladderOit.ts
 * from formulas on cited pages of a public Government of Manitoba guide (page text checked), with exact arithmetic.
 * Every task was fact-checked by a second model (gpt-6.2-sol) under owner authorization. Not human or exam-board reviewed. */\n`;
writeFileSync("server/deepGames/content/oit.ts",
  `import type { DeepCoursePackage } from "../../../shared/deepGames";\n\n${header}const data = ${JSON.stringify(pkg, null, 2)} satisfies DeepCoursePackage;\n\nexport default data;\n`);
const byMode: Record<string, number> = {}; for (const t of allTasks) byMode[t.mode] = (byMode[t.mode] ?? 0) + 1;
console.log("written; tasks by mode:", JSON.stringify(byMode), "bytes:", Buffer.byteLength(JSON.stringify(pkg)));
